# comparison Operator

a=27
b=20

print(f"{a}<{b}={a<b}")
print(f"{a}<={b}={a<=b}")
print(f"{a}>{b}={a>b}")
print(f"{a}>={b}={a>=b}")
print(f"{a}=={b}={a==b}")
print(f"{a}!={b}={a!=b}\n \n")

 # Logical Operators
# truth Tables of and, or and not

distance=40
time=25

print(distance>30 and time<20)
print(distance>30 or time<20)
print("not(distance>30 or time<20)\n")


